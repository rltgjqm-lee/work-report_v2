// date: "YYYY-MM-DD"
export const isWeekendOrHoliday = (date: string): boolean => {
  const dayOfWeek = new Date(`${date}T00:00:00`).getDay();
  if (dayOfWeek === 0 || dayOfWeek === 6) return true;

  return date in KOREAN_HOLIDAYS;
};
